import numpy as np 
arr_first = np.sum([[1, 2, 3], [4, 5, 6]])
print("Array sum:", arr_first)

arr_first= np.mean([[1, 2, 3], [4, 5, 6]])
print("Array mean:", arr_first)

arr_first= np.median([[1, 2, 3], [4, 5, 6]])
print("Array median:", arr_first)

arr_first= np.std([[1, 2, 3], [4, 5, 6]])
print("Array standard deviation:", arr_first)

arr_first= np.var([[1, 2, 3], [4, 5, 6]])
print("Array variance:", arr_first)

arr_first= np.min([[1, 2, 3], [4, 5, 6]])
print("Array minimum:", arr_first)

arr_first= np.max([[1, 2, 3], [4, 5, 6]])
print("Array maximum:", arr_first)