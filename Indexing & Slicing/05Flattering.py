import numpy as np

flattening_array = np.array([[1, 2, 3], [4, 5, 6]])
print("Original Array:")
print(flattening_array)

print("\nFlattening:")
print("Flattened Array:")
print(flattening_array.flatten())

ravel_array = np.array([[1, 2, 3], [4, 5, 6]])
print("\nRaveling:")    
print("Raveled Array:")
print(ravel_array.ravel())
